import {execFileSync} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
const source='https://raw.githubusercontent.com/holiday-jp/holiday_jp/master/holidays.yml';
// Download data only. Never evaluate upstream JavaScript or YAML code.
const yaml=execFileSync('curl',['--fail','--silent','--show-error','--location','--max-time','30',source],{encoding:'utf8',maxBuffer:1024*1024});
const dates={};
for(const line of yaml.split(/\r?\n/)){
 if(!line.trim()||line==='---'||line.startsWith('#'))continue;
 const match=/^(\d{4}-\d{2}-\d{2}): (.+)$/.exec(line);
 if(!match)throw new Error('Unexpected holiday calendar format');
 const [date,name]=match.slice(1);
 if(new Date(`${date}T12:00:00Z`).toISOString().slice(0,10)!==date||dates[date]||name.length>100)throw new Error('Invalid holiday entry');
 dates[date]=name;
}
const years=[...new Set(Object.keys(dates).map(d=>Number(d.slice(0,4))))].sort((a,b)=>a-b);
const currentYear=new Date().getUTCFullYear();
if(years[0]!==1970||years.at(-1)<currentYear+1||years.some((year,i)=>year!==1970+i||Object.keys(dates).filter(d=>d.startsWith(`${year}-`)).length<10))throw new Error('Incomplete holiday calendar');
if(dates['2024-02-23']!=='天皇誕生日'||!dates['2021-07-23']||!dates['2026-09-22'])throw new Error('Holiday calendar verification failed');
const metadata={source:'https://github.com/holiday-jp/holiday_jp',license:'MIT (licenses/holiday-jp.txt)',firstYear:years[0],lastYear:years.at(-1)};
const license=await readFile(new URL('../licenses/holiday-jp.txt',import.meta.url),'utf8');
await writeFile(new URL('../holidays.js',import.meta.url),`/*\n${license}*/\n// Generated by npm run holidays:update. Data: holiday_jp, MIT; see licenses/holiday-jp.txt.\nexport const HOLIDAY_CALENDAR = Object.freeze(${JSON.stringify(metadata)});\nexport const JAPAN_HOLIDAYS = Object.freeze(${JSON.stringify(dates,null,2)});\n`);
console.log(`Updated Japan holiday calendar: ${years[0]}–${years.at(-1)}, ${Object.keys(dates).length} dates`);
